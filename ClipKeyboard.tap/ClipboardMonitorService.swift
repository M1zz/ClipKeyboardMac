import AppKit
import Foundation

class ClipboardMonitorService {
    static let shared = ClipboardMonitorService()

    private var timer: Timer?
    private var lastChangeCount: Int = 0
    private var isMonitoring = false

    private init() {}

    func startMonitoring() {
        guard !isMonitoring else {
            print("⚠️ [ClipboardMonitor] 이미 모니터링 중입니다")
            return
        }

        isMonitoring = true
        lastChangeCount = NSPasteboard.general.changeCount

        // 1초마다 클립보드 변경 확인. macOS 는 클립보드 변경 알림이 없어 물어보는 수밖에 없다.
        // 여유(tolerance)를 주면 시스템이 다른 깨우기와 묶어 CPU 를 덜 깨운다 - 하루 종일 도는 타이머다.
        let timer = Timer(timeInterval: 1.0, repeats: true) { [weak self] _ in
            self?.checkClipboard()
        }
        timer.tolerance = 0.5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer

        print("✅ [ClipboardMonitor] 클립보드 모니터링 시작")
    }

    func stopMonitoring() {
        timer?.invalidate()
        timer = nil
        isMonitoring = false
        print("🛑 [ClipboardMonitor] 클립보드 모니터링 중지")
    }

    private func checkClipboard() {
        let pasteboard = NSPasteboard.general

        // 클립보드 변경 확인
        guard pasteboard.changeCount != lastChangeCount else {
            return
        }

        lastChangeCount = pasteboard.changeCount

        // 암호 관리자 등이 "기록하지 말라"고 표시한 복사는 담지 않는다(nspasteboard.org 관례).
        // 1Password · 키체인 접근 · 많은 암호 관리자가 이 표시를 붙인다.
        if let types = pasteboard.types, types.contains(where: Self.skippedTypes.contains) {
            print("🔒 [ClipboardMonitor] 기록하지 말라는 복사라 건너뜀")
            return
        }

        // 이미지가 있는지 확인. 종류만 먼저 본다 - 그림이 아닌 복사에서 그림을 풀어 보지 않게.
        if pasteboard.canReadObject(forClasses: [NSImage.self], options: nil),
           let image = pasteboard.readObjects(forClasses: [NSImage.self], options: nil)?.first as? NSImage {
            print("📸 [ClipboardMonitor] 이미지 감지됨")
            handleImageCopied(image)
            return
        }

        // 텍스트가 있는지 확인
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            // 복사한 내용은 로그에 남기지 않는다(암호 · 개인정보일 수 있다).
            print("📝 [ClipboardMonitor] 텍스트 감지됨 (\(text.count)자)")
            handleTextCopied(text)
            return
        }
    }

    /// 기록하지 말라는 표시. 감춘 것(암호), 잠깐 쓰는 것, 자동으로 만든 것.
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    private func handleTextCopied(_ text: String) {
        do {
            try MemoStore.shared.addToClipboardHistory(content: text)
            print("✅ [ClipboardMonitor] 텍스트 히스토리에 저장됨")
        } catch {
            print("❌ [ClipboardMonitor] 텍스트 저장 실패: \(error)")
        }
    }

    private func handleImageCopied(_ image: NSImage) {
        do {
            try MemoStore.shared.addImageToClipboardHistory(image: image)
            print("✅ [ClipboardMonitor] 이미지 히스토리에 저장됨")
        } catch {
            print("❌ [ClipboardMonitor] 이미지 저장 실패: \(error)")
        }
    }
}
